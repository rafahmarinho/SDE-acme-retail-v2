// Creates demo users (one per role + customers) and resets demo data (40 products, 60 orders).
// Usage: pnpm db:seed   (reads .env.local)
//
// Security notes:
// - Uses the service-role key, so it must only run on a trusted machine/CI (T19).
// - No password is committed (T76): DEMO_USER_PASSWORD from the environment, or a random one that
//   is printed once and written to the gitignored file .demo-credentials.local.
// - Demo identities are synthetic and use the reserved example.test domain (T544).
import { createClient } from "@supabase/supabase-js";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !serviceKey) {
  console.error("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required (see .env.example).");
  process.exit(1);
}

const password =
  process.env.DEMO_USER_PASSWORD || `Acme-${randomBytes(12).toString("base64url")}7a`;

const admin = createClient(url, serviceKey, { auth: { persistSession: false, autoRefreshToken: false } });

const staff = [
  { email: "admin@example.test", full_name: "Avery Admin", role: "admin" },
  { email: "catalog@example.test", full_name: "Casey Catalog", role: "catalog" },
  { email: "warehouse@example.test", full_name: "Wes Warehouse", role: "warehouse" },
  { email: "finance@example.test", full_name: "Frankie Finance", role: "finance" },
];
const customerNames = [
  "Alex Morgan", "Jordan Lee", "Taylor Brooks", "Riley Chen", "Sam Patel", "Jamie Rivera",
  "Morgan Diaz", "Quinn Foster", "Drew Kim", "Parker Nguyen", "Reese Walker", "Skyler Adams",
];
const customers = customerNames.map((full_name, i) => ({
  email: i === 0 ? "customer@example.test" : `${full_name.toLowerCase().replace(/\s+/g, ".")}@example.test`,
  full_name,
  role: "customer",
}));
const cities = [
  ["Springfield", "IL", "62701"], ["Riverton", "WY", "82501"], ["Fairview", "OR", "97024"],
  ["Lakeside", "CA", "92040"], ["Greenville", "SC", "29601"], ["Madison", "WI", "53703"],
];

async function findUserByEmail(email) {
  for (let page = 1; page < 20; page++) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 200 });
    if (error) throw error;
    const hit = data.users.find((u) => u.email === email);
    if (hit) return hit;
    if (data.users.length < 200) return null;
  }
  return null;
}

async function ensureUser({ email, full_name, role }, i) {
  let user;
  const { data, error } = await admin.auth.admin.createUser({
    email, password, email_confirm: true, user_metadata: { full_name },
  });
  if (error) {
    user = await findUserByEmail(email);
    if (!user) throw error;
    await admin.auth.admin.updateUserById(user.id, { password });
  } else {
    user = data.user;
  }
  const { error: pErr } = await admin.from("profiles").update({ role, full_name }).eq("id", user.id);
  if (pErr) throw pErr;
  if (role === "customer") {
    const [city, region, postal] = cities[i % cities.length];
    await admin.from("addresses").upsert(
      { user_id: user.id, full_name, line1: `${100 + i * 37} Market Street`, city, region, postal_code: postal,
        country: "US", is_default: true },
      { onConflict: "user_id,line1,postal_code,country", ignoreDuplicates: true },
    );
  }
  return user;
}

const all = [...staff, ...customers];
for (const [i, u] of all.entries()) {
  await ensureUser(u, i);
  process.stdout.write(".");
}
console.log(`\n${all.length} demo users ready.`);

const { data: reset, error: resetErr } = await admin.rpc("sim_reset");
if (resetErr) {
  console.error("sim_reset failed:", resetErr.message);
  process.exit(1);
}
console.log(`Demo data reset: ${reset.products} products, ${reset.orders} orders.`);

if (!process.env.DEMO_USER_PASSWORD) {
  writeFileSync(
    ".demo-credentials.local",
    `# Generated by scripts/seed.mjs - do not commit\n${all.map((u) => `${u.role.padEnd(9)} ${u.email}`).join("\n")}\npassword: ${password}\n`,
  );
  console.log("Generated a random demo password; see .demo-credentials.local (gitignored).");
} else {
  console.log("Demo users use DEMO_USER_PASSWORD from your environment.");
}
