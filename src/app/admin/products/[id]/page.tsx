import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { saveVariantAction, uploadImageAction } from "@/actions/admin";
import { ProductForm } from "@/components/admin/product-form";
import { ActionForm, SubmitButton } from "@/components/forms";
import { Badge, PageHeader, ProductImage } from "@/components/ui";
import { Uuid } from "@/lib/schemas";
import { requirePagePermission } from "@/services/auth";
import { getAdminProduct, listCategories } from "@/services/catalog";

export const metadata: Metadata = { title: "Edit product", robots: { index: false } };

export default async function EditProductPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ created?: string }> }) {
  const { id } = await params;
  if (!Uuid.safeParse(id).success) notFound();
  await requirePagePermission("catalog:write", `/admin/products/${id}`);
  const [product, categories] = await Promise.all([getAdminProduct(id), listCategories()]);
  if (!product) notFound();
  const created = (await searchParams).created;
  return (
    <div className="space-y-6">
      <PageHeader
        title={product.name}
        subtitle={<><Link href="/admin/products" className="link">Back to products</Link>{product.active && <> · <Link href={`/product/${product.slug}`} className="link">View in store</Link></>}</>}
      />
      {created && <p className="rounded-lg bg-brand-50 p-3 text-sm text-brand-800">Product created. Add variants and an image below.</p>}
      <div className="grid gap-6 xl:grid-cols-3">
        <section className="card p-5 xl:col-span-2">
          <h2 className="h2 mb-3">Details</h2>
          <ProductForm categories={categories} product={{ ...product, base_price: Number(product.base_price) }} />
        </section>
        <section className="card space-y-3 p-5">
          <h2 className="h2">Image</h2>
          <ProductImage name={product.name} path={product.image_path} accent={product.accent} />
          {/* Server-side checks: size, MIME and magic bytes; key generated by the server (T50, T214) */}
          <ActionForm action={uploadImageAction} className="space-y-2" encType="multipart/form-data">
            <input type="hidden" name="product_id" value={product.id} />
            <input type="file" name="image" accept="image/jpeg,image/png,image/webp" required className="block w-full text-sm" />
            <p className="text-xs text-gray-500">JPEG, PNG or WebP, up to 2 MB.</p>
            <SubmitButton className="btn-secondary" pendingText="Uploading...">Upload image</SubmitButton>
          </ActionForm>
        </section>
      </div>

      <section className="card p-5">
        <h2 className="h2 mb-3">Variants</h2>
        <div className="space-y-3">
          {product.variants.map((v) => (
            <ActionForm key={v.id} action={saveVariantAction} className="grid items-end gap-2 rounded-lg border border-gray-100 p-3 sm:grid-cols-6">
              <input type="hidden" name="product_id" value={product.id} />
              <input type="hidden" name="variant_id" value={v.id} />
              <label className="sm:col-span-2"><span className="label">Name</span><input name="name" className="input" defaultValue={v.name} maxLength={80} required /></label>
              <label><span className="label">SKU</span><input name="sku" className="input" defaultValue={v.sku} maxLength={40} required /></label>
              <label><span className="label">Price override</span><input name="price" type="number" step="0.01" min={0} className="input" defaultValue={v.price ?? ""} placeholder={String(product.base_price)} /></label>
              <label className="flex items-center gap-2 text-sm"><input type="checkbox" name="active" defaultChecked={v.active} /> Active</label>
              <div className="flex items-center gap-2">
                <SubmitButton className="btn-secondary btn-sm">Save</SubmitButton>
                <Badge tone={v.available > 5 ? "green" : v.available > 0 ? "amber" : "gray"}>{v.available} available</Badge>
              </div>
            </ActionForm>
          ))}
          <ActionForm action={saveVariantAction} className="grid items-end gap-2 rounded-lg border border-dashed border-gray-300 p-3 sm:grid-cols-6" resetOnSuccess>
            <input type="hidden" name="product_id" value={product.id} />
            <label className="sm:col-span-2"><span className="label">New variant name</span><input name="name" className="input" maxLength={80} required placeholder="e.g. Size M" /></label>
            <label><span className="label">SKU</span><input name="sku" className="input" maxLength={40} required placeholder="AC000-M" /></label>
            <label><span className="label">Price override</span><input name="price" type="number" step="0.01" min={0} className="input" placeholder={String(product.base_price)} /></label>
            <label className="flex items-center gap-2 text-sm"><input type="checkbox" name="active" defaultChecked /> Active</label>
            <SubmitButton className="btn-primary btn-sm">Add variant</SubmitButton>
          </ActionForm>
          <p className="text-xs text-gray-500">Stock is managed by the inventory team on the Inventory page.</p>
        </div>
      </section>
    </div>
  );
}
